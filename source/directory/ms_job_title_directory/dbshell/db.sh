#!/bin/bash
psql -v ON_ERROR_STOP=1 --username "postgres" --dbname "postgres" <<-EOSQL
  CREATE DATABASE ${DB_NAME};
  CREATE USER ${DB_USER} WITH PASSWORD '${DB_PASSWORD}';
  GRANT ALL PRIVILEGES ON DATABASE ${DB_NAME} TO ${DB_USER};
EOSQL

psql -v ON_ERROR_STOP=1 --username "postgres" --dbname "${DB_NAME}" <<-EOSQL
    GRANT USAGE, CREATE ON SCHEMA public TO ${DB_USER};
EOSQL

psql -v ON_ERROR_STOP=1 --username "${DB_USER}" --dbname "${DB_NAME}" <<-EOSQL
  CREATE TABLE public.${DB_TABLENAME} (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 text,
    name_genitive        text NOT NULL DEFAULT '',
    name_dative          text NOT NULL DEFAULT '',
    name_accusative      text NOT NULL DEFAULT '',
    name_instrumental    text NOT NULL DEFAULT '',
    name_prepositional   text NOT NULL DEFAULT '',
    description          text,
	id_basis             bigint,
	endpoint_basis         text NOT NULL DEFAULT '',
    status               smallint default 1,
	prefix               smallint,
	id_transaction       text,
	UNIQUE (id, id_basis)
	);

  COMMENT ON TABLE  ${DB_TABLENAME}                 IS 'Job title directory';
  COMMENT ON COLUMN ${DB_TABLENAME}.name            IS 'Directory name (nominative)';
  COMMENT ON COLUMN ${DB_TABLENAME}.name_genitive   IS 'Directory name, genitive case';
  COMMENT ON COLUMN ${DB_TABLENAME}.name_dative     IS 'Directory name, dative case';
  COMMENT ON COLUMN ${DB_TABLENAME}.name_accusative IS 'Directory name, accusative case';
  COMMENT ON COLUMN ${DB_TABLENAME}.name_instrumental IS 'Directory name, instrumental case';
  COMMENT ON COLUMN ${DB_TABLENAME}.name_prepositional IS 'Directory name, prepositional case';
  COMMENT ON COLUMN ${DB_TABLENAME}.description     IS 'Directory description';
  COMMENT ON COLUMN ${DB_TABLENAME}.id_basis        IS 'Id basis';
  COMMENT ON COLUMN ${DB_TABLENAME}.endpoint_basis IS 'Basis endpoint';
  COMMENT ON COLUMN ${DB_TABLENAME}.status          IS 'Directory status (0 - deleted, 1 - saved)';
  COMMENT ON COLUMN ${DB_TABLENAME}.prefix          IS 'Prefix of DB';
  COMMENT ON COLUMN ${DB_TABLENAME}.id_transaction  IS 'Transaction Id';

EOSQL
