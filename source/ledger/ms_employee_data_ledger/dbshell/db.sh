#!/bin/bash
psql -v ON_ERROR_STOP=1 --username "postgres" --dbname "postgres" <<-EOSQL
  CREATE DATABASE ${DB_NAME};
  CREATE USER ${DB_USER} WITH PASSWORD '${DB_PASSWORD}';
  GRANT ALL PRIVILEGES ON DATABASE ${DB_NAME} TO ${DB_USER};
EOSQL

psql -v ON_ERROR_STOP=1 --username "postgres" --dbname "${DB_NAME}" <<-EOSQL
    GRANT USAGE, CREATE ON SCHEMA public TO ${DB_USER};
EOSQL

psql -v ON_ERROR_STOP=1 --username "${DB_USER}" --dbname "${DB_NAME}" <<-EOSQL
  CREATE TABLE public.${DB_TABLENAME} (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ddate                timestamp,
    endpoint             text NOT NULL,
    id_document          bigint NOT NULL,
    id_employee          bigint NOT NULL,
    delta                integer NOT NULL,
    balance              bigint NOT NULL DEFAULT 0,
    UNIQUE (id_document, id_employee)
	);

  COMMENT ON TABLE  ${DB_TABLENAME}                      IS 'Employee data ledger: staff headcount balances';
  COMMENT ON COLUMN ${DB_TABLENAME}.id                   IS 'Lager ID';
  COMMENT ON COLUMN ${DB_TABLENAME}.ddate                IS 'Record date';
  COMMENT ON COLUMN ${DB_TABLENAME}.endpoint             IS 'Originating document type';
  COMMENT ON COLUMN ${DB_TABLENAME}.id_document          IS 'Originating document';
  COMMENT ON COLUMN ${DB_TABLENAME}.id_employee          IS 'Employee ID';
  COMMENT ON COLUMN ${DB_TABLENAME}.delta                IS 'Headcount change (+1/-1), the only write input';
  COMMENT ON COLUMN ${DB_TABLENAME}.balance              IS 'Accumulated headcount, server-computed';

EOSQL
